import { existsSync, mkdtempSync, writeFileSync } from "node:fs";
import { createServer } from "node:http";
import type { AddressInfo } from "node:net";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { loadConfig } from "../src/config/config.ts";
import { createRepositories } from "../src/db/repositories/index.ts";
import type { Trace } from "../src/domain/trace.ts";
import { createApp } from "../src/http/app.ts";
import { ROOT } from "../src/http/static.ts";
import { NoEngineError } from "../src/services/errors.ts";
import { SettingsManager } from "../src/services/settings.ts";
import { SpendGuard } from "../src/services/spend-guard.ts";
import { CASES, FIXTURES, type Result } from "./cases.ts";

// Runs the real app on a throwaway SQLite file, so the user's own chats are never touched.
if (existsSync(join(ROOT, ".env"))) process.loadEnvFile(join(ROOT, ".env"));
process.env.DAILY_BUDGET_USD ??= "5";
const dir = mkdtempSync(join(tmpdir(), "mino-eval-"));
const config = loadConfig(process.env);
const settings = new SettingsManager(join(dir, "settings.json"), config);
const active = settings.active();
if (!active) {
  console.error("Add a GEMINI_API_KEY, ANTHROPIC_API_KEY or OPENAI_API_KEY to .env to run the evals.");
  process.exit(1);
}
const store = createRepositories(join(dir, "eval.db"));
const ist = ([y, mo, d, h, mi]: readonly number[]) => Date.UTC(y, mo - 1, d, h, mi) - 330 * 60_000;
for (const f of FIXTURES) store.turns.save({ threadId: f.threadId, createdAt: ist(f.at), userText: f.question, assistantText: f.answer, sources: [], queries: [], status: "ok" });

const server = createServer(
  createApp({
    store,
    settings,
    guard: new SpendGuard(store.usage, config.limits),
    currentModel: () => settings.active()?.model ?? "unknown",
    helpers: () => settings.helpers(),
    run: (options) => settings.engine()?.run(options) ?? Promise.reject(new NoEngineError()),
  }),
);
await new Promise<void>((r) => server.listen(0, "127.0.0.1", r));
const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;

async function ask(thread: string, message: string): Promise<Result> {
  const before = store.traces.ofThread(thread).length;
  const body = await (await fetch(`${base}/api/chat`, { method: "POST", body: JSON.stringify({ threadId: thread, message, timezone: "Asia/Kolkata" }) })).text();
  const text = body.split("\n").filter((l) => l.startsWith("data: ")).map((l) => JSON.parse(l.slice(6))).filter((e) => e.type === "text").map((e) => e.text).join("");
  const trace = store.traces.ofThread(thread)[before];
  if (!trace) throw new Error(`No trace for "${message}". Reply: ${body.slice(0, 300)}`);
  return { text, trace };
}

console.log(`Running ${CASES.length} cases on ${active.provider} ${active.model}, effort ${config.effort}`);
const rows: { id: string; message: string; passed: boolean; checks: [string, boolean][]; result: Result }[] = [];
for (const c of CASES) {
  if (c.setup) await ask(c.setup.thread, c.setup.message);
  const result = await ask(c.thread, c.message);
  const checks = c.checks.map(([label, passes]) => [label, passes(result)] as [string, boolean]);
  const passed = checks.every(([, ok]) => ok);
  rows.push({ id: c.id, message: c.message, passed, checks, result });
  console.log(`${passed ? "PASS" : "FAIL"}  ${c.id}  (${(result.trace.totalMs / 1000).toFixed(1)} s, $${result.trace.costUsd.toFixed(4)})`);
}
server.closeAllConnections();
server.close();

const traces = rows.map((r) => r.result.trace);
const median = (xs: number[]) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)] ?? 0;
const s = (ms: number | null) => (ms === null ? "—" : `${(ms / 1000).toFixed(1)} s`);
const passedCount = rows.filter((r) => r.passed).length;
const cost = traces.reduce((n, t) => n + t.costUsd, 0);
const date = new Date().toISOString().slice(0, 10);
const lookups = (t: Trace) =>
  t.spans.filter((x) => x.name === "search_history").map((x) => Object.entries(x.attributes).filter(([k]) => k !== "result").map(([k, v]) => `${k}=${v}`).join(" ")).join("; ") || "none";
const escape = (text: string) => text.replaceAll("|", "\\|").replaceAll("\n", " ");

const report = `# Mino eval report

Generated by \`npm run eval\` on ${date}. Every number below comes from the reply's own trace, recorded by the app while it answered.

| Model | Thinking | Cases passed | Median first text | Median total | Cost of this run |
| --- | --- | --- | --- | --- | --- |
| ${active.model} | ${config.effort} | **${passedCount} / ${rows.length}** | ${s(median(traces.flatMap((t) => (t.firstTokenMs === null ? [] : [t.firstTokenMs]))))} | ${s(median(traces.map((t) => t.totalMs)))} | $${cost.toFixed(2)} |

The app runs as it does for a user: the HTTP stream, a fresh SQLite database seeded with four past chats from 3, 7 and 9 November 2026, live web search, and the \`search_history\` tool. Checks are plain code over the answer and the trace, with no model grading. Gemini reports its web searches together with the answer, so those steps show at the end of a trace rather than when they ran.

| Case | Result | History lookups | Web searches | First text | Total | Cost |
| --- | --- | --- | --- | --- | --- | --- |
${rows.map((r) => `| ${r.id} | ${r.passed ? "pass" : "**fail**"} | ${escape(lookups(r.result.trace))} | ${r.result.trace.webSearches} | ${s(r.result.trace.firstTokenMs)} | ${s(r.result.trace.totalMs)} | $${r.result.trace.costUsd.toFixed(4)} |`).join("\n")}

## Each case

${rows
  .map(
    (r) => `<details>
<summary><b>${r.id}</b>: ${r.passed ? "pass" : "fail"}<br>Asked: <i>${r.message}</i></summary>

${r.checks.map(([label, ok]) => `- ${ok ? "✓" : "✗"} ${label}`).join("\n")}

**Steps:**
${r.result.trace.spans.map((x) => `- \`${x.name}\` at ${s(x.startMs)}${x.durationMs ? `, ${x.durationMs} ms` : ""}${Object.keys(x.attributes).length ? `: ${Object.entries(x.attributes).map(([k, v]) => `${k}=${v}`).join(", ")}` : ""}`).join("\n")}

**Answer:**

${r.result.text.split("\n").map((l) => `> ${l}`).join("\n")}

</details>`,
  )
  .join("\n\n")}
`;

writeFileSync(join(ROOT, "evals", "REPORT.md"), report);
console.log(`\n${passedCount} / ${rows.length} passed, $${cost.toFixed(3)}. Wrote evals/REPORT.md`);
store.close();
